import { mkdir, readFile, writeFile } from "node:fs/promises";
import { formatSource } from "../../../tools/code-tools.mjs";

export const SEGMENTS = 96;
export const SEGMENT_UNITS = 1024;
export const LAP_UNITS = SEGMENTS * SEGMENT_UNITS;
const quantize = (value) => Math.round(value * 256) / 256;
const centers = Array.from({ length: SEGMENTS }, (_, i) => {
  const t = (i / SEGMENTS) * Math.PI * 2;
  return [
    quantize(Math.sin(t) * 58 + Math.sin(t * 2) * 12),
    quantize(2 + Math.sin(t * 2) * 2.5),
    quantize(Math.cos(t) * 42 + Math.sin(t * 3) * 7),
  ];
});
export const course = centers.map((point, i) => {
  const next = centers[(i + 1) % SEGMENTS];
  const after = centers[(i + 2) % SEGMENTS];
  const yaw = Math.atan2(next[0] - point[0], next[2] - point[2]);
  let turn = Math.atan2(after[0] - next[0], after[2] - next[2]) - yaw;
  while (turn > Math.PI) {
    turn -= 2 * Math.PI;
  }
  while (turn < -Math.PI) {
    turn += 2 * Math.PI;
  }
  const pitch = -Math.atan2(next[1] - point[1], Math.hypot(next[0] - point[0], next[2] - point[2]));
  const angle = (v) => Math.round(v * 65536) / 65536;
  return [
    ...point,
    quantize(Math.sin(yaw)),
    quantize(Math.cos(yaw)),
    Math.round(turn * 512),
    angle(yaw),
    angle(pitch),
  ];
});

export async function generateCourse(write = false) {
  const rows = course.map((row) => `{${row.join(",")}}`).join(",\n");
  const sources = {
    "examples/kart3d/odin/course/course.odin": `// Generated by examples/kart3d/tools/course.mjs.\npackage course\nPoint :: [8]f64\nPOINTS := [96]Point{${rows},}\n`,
    "examples/kart3d/luau/course.luau": `--!strict\n-- Generated by examples/kart3d/tools/course.mjs.\nreturn {${rows}}\n`,
  };
  for (const [path, source] of Object.entries(sources)) {
    const formatted = formatSource(source, path);
    if (write) {
      await mkdir(path.slice(0, path.lastIndexOf("/")), { recursive: true });
      await writeFile(path, formatted);
    } else if ((await readFile(path, "utf8")) !== formatted) {
      throw new Error(`Stale course data: ${path}; run mise run //examples/kart3d:generate`);
    }
  }
}
