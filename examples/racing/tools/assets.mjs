import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { bundleLuau, odinEntry } from "../../../tools/sdk/bundle.mjs";
import { formatSource } from "../../../tools/code-tools.mjs";
import { graphicsPacket } from "../../../tools/sdk/assets.mjs";
// Original 16×16 artwork. Every cartridge receives this same packed atlas.
const colors = [
  "#17202e",
  "#7bbbd0",
  "#577e91",
  "#476b40",
  "#517b43",
  "#52545d",
  "#5c5e68",
  "#304853",
  "#d45d48",
  "#5696c9",
  "#f3c969",
  "#f4ecd6",
  "#e78b55",
  "#8dad61",
  "#926f99",
  "#afc8c6",
];
const palette = colors.map(
  (c) => (0xff000000 | parseInt(c.slice(5, 7) + c.slice(3, 5) + c.slice(1, 3), 16)) >>> 0,
);
function image(draw) {
  const rows = Array.from({ length: 16 }, () => Array(16).fill(255));
  const box = (x, y, w, h, c) => {
    for (let py = y; py < y + h; py++) {
      for (let px = x; px < x + w; px++) {
        if (px >= 0 && px < 16 && py >= 0 && py < 16) {
          rows[py][px] = c;
        }
      }
    }
  };
  draw(box);
  return rows.flat();
}
const kart = (color, lean = 0) =>
  image((b) => {
    b(1, 12, 14, 3, 7);
    b(1, 9, 3, 6, 0);
    b(12, 9, 3, 6, 0);
    b(4, 7, 8, 8, color);
    b(3, 11, 10, 3, color);
    b(5 + lean, 3, 6, 6, 0);
    b(5 + lean, 2, 6, 4, 11);
    b(6 + lean, 2, 4, 2, color);
    b(5, 9, 6, 2, 7);
    b(4, 14, 8, 1, 11);
    b(5, 12, 2, 1, 10);
    b(9, 12, 2, 1, 10);
  });
const sprites = [
  kart(8),
  kart(9),
  kart(10),
  kart(13),
  image((b) => {
    b(7, 7, 2, 9, 8);
    b(2, 4, 12, 6, 3);
    b(4, 1, 8, 8, 13);
    b(6, 0, 4, 4, 13);
  }),
  image((b) => {
    b(7, 6, 2, 10, 7);
    b(1, 2, 14, 8, 0);
    b(2, 3, 12, 6, 10);
    b(5, 4, 3, 4, 8);
    b(8, 5, 3, 2, 8);
  }),
  image((b) => {
    b(1, 7, 14, 5, 11);
    b(3, 4, 10, 7, 11);
    b(6, 2, 5, 9, 11);
  }),
  kart(8, -1),
  kart(8, 1),
];
const font = JSON.parse(await readFile("examples/rpg/shared/assets.json", "utf8")).font;
const rows = sprites.map((pixels) =>
  Array.from({ length: 16 }, (_, y) =>
    pixels
      .slice(y * 16, y * 16 + 16)
      .map((ink) => (ink === 255 ? "." : ink.toString(16)))
      .join(""),
  ),
);
const { packet } = graphicsPacket({ palette: colors, sprites: rows, font });
await mkdir("examples/racing/odin/assets", { recursive: true });
await mkdir("examples/racing/build/assets", { recursive: true });
await writeFile(
  "examples/racing/build/assets/cover-assets.json",
  JSON.stringify({ title: "Copper Circuit", palette: colors, sprites: rows, font }),
);
await writeFile(
  "examples/racing/odin/assets/assets.odin",
  formatSource(
    `// Generated by examples/racing/tools/assets.mjs.\npackage assets\npalette := [16]u32{${palette}}\nraster := [${packet.length}]u8{${[...packet]}}\n`,
    "examples/racing/odin/assets/assets.odin",
  ),
);
await writeFile("examples/racing/odin/cartridge.odin", odinEntry({ display: "Low" }));
await writeFile(
  "examples/racing/luau/assets.luau",
  formatSource(
    `--!strict\n-- Generated shared palette.\nreturn {palette={${palette}}}\n`,
    "examples/racing/luau/assets.luau",
  ),
);
await writeFile(
  "examples/racing/build/assets/racing.luau",
  await bundleLuau({
    entry: resolve("examples/racing/luau/main.luau"),
    project: resolve("examples/racing/luau"),
    sdkRoot: resolve("sdk/luau"),
    assets: packet,
    display: [320, 180],
  }),
);
console.log("Racing atlas and Luau cartridge bundled.");
