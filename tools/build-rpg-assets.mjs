import { readFile, writeFile, mkdir } from 'node:fs/promises';

const source = JSON.parse(await readFile('examples/rpg-shared/assets.json', 'utf8'));
const json = value => JSON.stringify(value);
const palette = source.palette.map(hex => (0xff000000 | parseInt(hex.slice(5,7)+hex.slice(3,5)+hex.slice(1,3),16)) >>> 0);
const assets = { ...source, palette };
const dir = 'examples/rpg-odin/assets';
await mkdir(dir, { recursive: true });
const lines = ['// Generated by tools/build-rpg-assets.mjs from the shared cartridge assets.', 'package assets',
  `palette := [${palette.length}]u32{${palette.join(',')}}`,
  `sprites := [${assets.sprites.length}][16]string{${assets.sprites.map(rows => `{${rows.map(json).join(',')}}`).join(',')}}`,
  `world := [${assets.world.length}]string{${assets.world.map(json).join(',')}}`,
  'glyph :: proc(c: u8) -> [7]string {', 'switch c {'];
for (const [c, rows] of Object.entries(assets.font)) lines.push(`case ${c.charCodeAt(0)}: return {${rows.map(json).join(',')}}`);
lines.push('}', 'return {}', '}');
await writeFile(`${dir}/assets.odin`, lines.join('\n')+'\n');
const luaValue = value => Array.isArray(value) ? `{${value.map(luaValue).join(',')}}` :
  value && typeof value === 'object' ? `{${Object.entries(value).map(([k,v])=>`[${json(k)}]=${luaValue(v)}`).join(',')}}` : json(value);
await mkdir('build/rpg', { recursive: true });
const helpers = await readFile('examples/rpg-luau/graphics.luau','utf8');
const game = await readFile('examples/rpg-luau/main.luau','utf8');
await writeFile('build/rpg/main.luau', `-- Generated cartridge source: shared assets, SDK, game.\nlocal assets = ${luaValue(assets)}\n${helpers}\n${game}`);
console.log('Shared RPG assets and Luau cartridge bundled.');
