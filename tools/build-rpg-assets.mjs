import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { bundleLuau, odinEntry } from "./sdk/bundle.mjs";
import { formatSource } from "./code-tools.mjs";
import { graphicsPacket } from "./sdk/assets.mjs";

const source = JSON.parse(await readFile("examples/rpg-shared/assets.json", "utf8"));
const json = (value) => JSON.stringify(value);
const palette = source.palette.map(
  (hex) => (0xff000000 | parseInt(hex.slice(5, 7) + hex.slice(3, 5) + hex.slice(1, 3), 16)) >>> 0,
);
const assets = { ...source, palette };
const { packet } = graphicsPacket(source);
const dir = "examples/rpg-odin/assets";
await mkdir(dir, { recursive: true });
const lines = [
  "// Generated by tools/build-rpg-assets.mjs from the shared cartridge assets.",
  "package assets",
  `palette := [${palette.length}]u32{${palette.join(",")}}`,
  `sprites := [${assets.sprites.length}][16]string{${assets.sprites.map((rows) => `{${rows.map(json).join(",")}}`).join(",")}}`,
  `world := [${assets.world.length}]string{${assets.world.map(json).join(",")}}`,
  `raster := [${packet.length}]u8{${[...packet].join(",")}}`,
  "glyph :: proc(c: u8) -> [7]string {",
  "switch c {",
];
for (const [c, rows] of Object.entries(assets.font)) {
  lines.push(`case ${c.charCodeAt(0)}: return {${rows.map(json).join(",")}}`);
}
lines.push("}", "return {}", "}");
await writeFile(`${dir}/assets.odin`, formatSource(lines.join("\n") + "\n", `${dir}/assets.odin`));
const luaValue = (value) =>
  Array.isArray(value)
    ? `{${value.map(luaValue).join(",")}}`
    : value && typeof value === "object"
      ? `{${Object.entries(value)
          .map(([k, v]) => `[${json(k)}]=${luaValue(v)}`)
          .join(",")}}`
      : json(value);
await mkdir("build/rpg", { recursive: true });
await writeFile(
  "examples/rpg-luau/assets.luau",
  formatSource(
    `--!strict\n-- Generated shared palette and map.\nreturn ${luaValue({ palette, world: assets.world })}\n`,
    "examples/rpg-luau/assets.luau",
  ),
);
await writeFile("examples/rpg-odin/cartridge.odin", odinEntry());
await writeFile(
  "build/rpg/batched.luau",
  await bundleLuau({
    entry: resolve("examples/rpg-luau/main.luau"),
    project: resolve("examples/rpg-luau"),
    sdkRoot: resolve("sdk/luau"),
    assets: packet,
  }),
);
console.log("Shared RPG assets and Luau cartridge bundled.");
