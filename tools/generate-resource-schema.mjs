import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const schema = JSON.parse(await readFile(new URL("sdk/proposals/resource-transport.json", root)));
const constants = Object.fromEntries(
  Object.entries(schema).filter(([, value]) => typeof value === "number"),
);
for (const [name, value] of Object.entries(schema.opcodes)) {
  constants[`op_${name}`] = value;
}
for (const [name, value] of Object.entries(schema.formats)) {
  constants[`format_${name}`] = value;
}
const files = {
  "runtime/odin/resourcewire/schema.odin":
    "// Generated by tools/generate-resource-schema.mjs.\npackage resourcewire\n\n" +
    Object.entries(constants)
      .map(([key, value]) => `${key} :: ${value}\n`)
      .join(""),
  "sdk/luau/resource_schema.luau":
    "--!strict\n-- Generated by tools/generate-resource-schema.mjs.\nreturn table.freeze({\n" +
    Object.entries(constants)
      .map(([key, value]) => `    ${key} = ${value},\n`)
      .join("") +
    "})\n",
  "experiments/luau-executor/resource_schema.h":
    "// Generated by tools/generate-resource-schema.mjs.\n#pragma once\nnamespace resource_schema {\n" +
    Object.entries(constants)
      .map(([key, value]) => `constexpr unsigned ${key} = ${value};\n`)
      .join("") +
    "}\n",
};
for (const [file, content] of Object.entries(files)) {
  const target = new URL(file, root);
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== content) {
      throw new Error(`Stale generated resource schema: ${fileURLToPath(target)}`);
    }
  } else {
    await writeFile(target, content);
  }
}
console.log(`Resource schema ${process.argv.includes("--check") ? "checked" : "generated"}.`);
