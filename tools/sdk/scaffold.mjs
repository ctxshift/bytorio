import { readFile, writeFile, mkdir, lstat } from "node:fs/promises";
import { resolve } from "node:path";

async function ordinaryOutput(path, directory = false) {
  try {
    const info = await lstat(path);
    if (directory ? !info.isDirectory() : !info.isFile()) {
      throw new Error("Generated SDK/editor paths cannot be symbolic links or special files");
    }
  } catch (error) {
    if (error.code !== "ENOENT") {
      throw error;
    }
  }
}

/**
 * @param {{readAsset: (path: string) => Promise<string>, branding: {starterTitle: string, starterMessage: string}}} options
 */
export async function createScaffolder({ readAsset, branding }) {
  const contract = JSON.parse(await readAsset("sdk/contract.json"));
  async function syncEditor(project) {
    const target = resolve(project, ".bytorio");
    await ordinaryOutput(target, true);
    await mkdir(target, { recursive: true });
    for (const file of [
      "bytorio.luau",
      "native.luau",
      "resources.luau",
      "math3d.luau",
      "billboard.luau",
      "ogg.luau",
      "resource_schema.luau",
      "constants.luau",
      "content.luau",
      "save.luau",
      "text.luau",
    ]) {
      await ordinaryOutput(resolve(target, file));
      await writeFile(resolve(target, file), await readAsset(`sdk/luau/${file}`));
    }
    const settingsPath = resolve(project, ".luaurc");
    await ordinaryOutput(settingsPath);
    let settings = { languageMode: "strict" };
    try {
      settings = JSON.parse(await readFile(settingsPath, "utf8"));
    } catch (error) {
      if (error.code !== "ENOENT") {
        throw error;
      }
    }
    settings.aliases = { ...settings.aliases, bytorio: "./.bytorio/bytorio" };
    // Remove only the alias previously generated by this SDK; user aliases survive.
    if (settings.aliases.console === "./.console/console") {
      delete settings.aliases.console;
    }
    await writeFile(settingsPath, JSON.stringify(settings, null, 2) + "\n");
    const ignorePath = resolve(project, ".gitignore");
    await ordinaryOutput(ignorePath);
    let ignore = "";
    try {
      ignore = await readFile(ignorePath, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") {
        throw error;
      }
    }
    if (!ignore.split(/\r?\n/).includes(".bytorio/")) {
      await writeFile(
        ignorePath,
        ignore + (ignore && !ignore.endsWith("\n") ? "\n" : "") + ".bytorio/\n",
      );
    }
  }
  async function createProject(path, language = "luau") {
    if (!["luau", "odin"].includes(language)) {
      throw new Error("language must be luau or odin");
    }
    const project = resolve(path);
    // Exclusive creation preserves existing folders and user files.
    await mkdir(project);
    await mkdir(resolve(project, "src"));
    await writeFile(
      resolve(project, "console.json"),
      JSON.stringify(
        {
          sdk: contract.sdkVersion,
          profile: contract.profile,
          title: branding.starterTitle,
          language,
          entry: language === "luau" ? "src/main.luau" : "src",
          assets: "assets.json",
          display: [640, 360],
        },
        null,
        2,
      ) + "\n",
    );
    await writeFile(resolve(project, ".gitignore"), "build/\n.bytorio/\n");
    await writeFile(
      resolve(project, ".luaurc"),
      JSON.stringify(
        { languageMode: "strict", aliases: { bytorio: "./.bytorio/bytorio" } },
        null,
        2,
      ) + "\n",
    );
    if (language === "luau") {
      await mkdir(resolve(project, ".vscode"));
      await writeFile(
        resolve(project, ".vscode/settings.json"),
        await readAsset("sdk/templates/luau-settings.json"),
      );
    }
    const extension = language === "luau" ? "luau" : "odin";
    const template = await readAsset(`sdk/templates/main.${extension}`);
    await writeFile(
      resolve(project, `src/main.${extension}`),
      template.replaceAll("__STARTER_MESSAGE__", branding.starterMessage),
    );
    await writeFile(resolve(project, "assets.json"), await readAsset("sdk/templates/assets.json"));
    await syncEditor(project);
    console.log(`Created ${language} project: ${path}`);
    return project;
  }

  return { createProject, syncEditor };
}
